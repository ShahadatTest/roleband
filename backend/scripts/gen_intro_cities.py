"""Regenerate `dashboard/src/introCities.gen.ts`: the cities the welcome planet draws.

Dev-only and offline: it reads the committed `tracker/taxonomy/cities.tsv`, so a
regeneration follows a new city table and nothing else.

Which cities, and why:

* Biggest first. A city of `_FLOOR` people or more is kept only when no city
  already kept lies within `_SPACING` degrees of it, so the dots spread across a
  country instead of piling into its densest region (population alone would
  give China and India most of the planet).
* Every tracked country keeps its largest city, closer to a neighbour than the
  spacing allows if need be (`_MIN_GAP`), so a small country still shows.
* No city in `_EXCLUDED`: those countries stay tracked everywhere else in the
  app; the welcome picture alone leaves them blank.

Run:  .venv/bin/python -m scripts.gen_intro_cities [--check]

`--check` regenerates in memory and diffs against the committed file.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

from tracker.taxonomy.countries import COUNTRIES

_ROOT = Path(__file__).resolve().parents[2]
_TABLE = _ROOT / "backend" / "tracker" / "taxonomy" / "cities.tsv"
OUT = _ROOT / "dashboard" / "src" / "introCities.gen.ts"

_FLOOR = 250_000
_SPACING = 3.0
_MIN_GAP = 1.0
#: ISO 3166-1 alpha-2 codes the welcome planet draws no cities in.
_EXCLUDED = frozenset({"RU"})

_HEADER = """\
// Cities the welcome planet draws, GENERATED by backend/scripts/gen_intro_cities.py
// from backend/tracker/taxonomy/cities.tsv: do not edit by hand.
//
// Source: GeoNames (https://www.geonames.org), licence CC-BY-4.0. See
// docs/third-party.md.

/** [lon, lat] of each city, biggest first. */
export const INTRO_CITIES: readonly (readonly [number, number])[] = [
"""


def _degrees_apart(a: tuple[float, float], b: tuple[float, float]) -> float:
    """Great-circle distance between two (lon, lat) points, in degrees."""
    lon1, lat1, lon2, lat2 = map(math.radians, (*a, *b))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return math.degrees(2 * math.asin(min(1.0, math.sqrt(h))))


def select(rows: list[tuple[str, int, float, float]]) -> list[tuple[float, float]]:
    """(country, population, lon, lat) rows to the cities drawn, as (lon, lat)."""
    tracked = {c.alpha2.upper() for c in COUNTRIES} - _EXCLUDED
    ranked = sorted((r for r in rows if r[0] in tracked), key=lambda r: (-r[1], r[2], r[3]))
    kept: list[tuple[float, float]] = []
    seen: set[str] = set()

    def clear(point: tuple[float, float], gap: float) -> bool:
        return all(_degrees_apart(point, other) >= gap for other in kept)

    for country, population, lon, lat in ranked:
        largest = country not in seen
        seen.add(country)
        if (largest and clear((lon, lat), _MIN_GAP)) or (population >= _FLOOR and clear((lon, lat), _SPACING)):
            kept.append((lon, lat))
    return kept


def read_table(path: Path = _TABLE) -> list[tuple[str, int, float, float]]:
    rows = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if line.startswith("#") or not line.strip():
                continue
            f = line.rstrip("\n").split("\t")
            rows.append((f[3], int(f[6] or 0), float(f[8]), float(f[7])))
    return rows


def build() -> str:
    lines = [f"  [{lon:.2f}, {lat:.2f}],\n" for lon, lat in select(read_table())]
    return _HEADER + "".join(lines) + "];\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="diff against the committed file")
    args = ap.parse_args()
    text = build()
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date; rerun without --check", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({text.count(chr(10)) - _HEADER.count(chr(10)) - 1} cities)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
