"""Regenerate `tracker/taxonomy/cities.tsv` from the GeoNames snapshot.

Dev-only, like `scripts.gen_country_table`: the generated table is committed
and reviewed in diff, and nothing at runtime fetches GeoNames. The snapshot is
pinned in `tracker.vendored` (`geonames-cities15000`, `geonames-admin1`) by the
sha256 of what was fetched; GeoNames republishes its dumps daily in place, so a
regeneration is a deliberate step to a newer snapshot: fetch, review the diff,
update the recorded date and hashes.

What is kept, and why:

* Populated places of 15,000 people or more (the standard `cities15000`
  extract), in the countries our taxonomy tracks.
* Feature codes for real towns and cities only. Districts (`PPLX`) have no
  parent city in the dump, and historical, abandoned or destroyed places are
  not places anyone works.
* A city named exactly like its own country (Singapore, Luxembourg, Monaco) is
  left out: the country already is that place, and two rows for one answer is
  the duplicate the search would show.
* Alternate names only in proper-cased Latin script. That keeps the English
  exonyms postings use ("Bangalore", "Gurgaon", "Kiev") and drops the
  lower-cased transliterations and codes GeoNames also carries.

Run:  .venv/bin/python -m scripts.gen_city_table [--check] [--from DIR]

`--from DIR` reads `cities15000.zip` and `admin1CodesASCII.txt` from a local
directory instead of fetching (their hashes are still checked). `--check`
regenerates in memory and diffs against the committed file.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import sys
import unicodedata
import zipfile
from pathlib import Path

import httpx

from tracker.taxonomy.countries import COUNTRIES
from tracker.vendored import by_name

_OUT = Path(__file__).resolve().parents[1] / "tracker" / "taxonomy" / "cities.tsv"

#: GeoNames feature codes kept: towns, seats of government, capitals.
_KEEP_FEATURES = frozenset({"PPL", "PPLA", "PPLA2", "PPLA3", "PPLA4", "PPLA5", "PPLC", "PPLG"})

COLUMNS = (
    "geonameid", "name", "asciiname", "country", "admin1", "admin1_name",
    "population", "lat", "lon", "feature", "alternates",
)

_HEADER = (
    "# Cities: GeoNames cities15000, GENERATED by backend/scripts/gen_city_table.py. Do not edit by hand.\n"
    "# Source: GeoNames (https://www.geonames.org), licence CC-BY-4.0. Snapshot {snapshot}.\n"
    "# Kept: populated places of 15,000+ in tracked countries; no districts; Latin-script alternates.\n"
    "# " + "\t".join(COLUMNS) + "\n"
)


def fold(text: str) -> str:
    """Lowercase ASCII: 'Göteborg' -> 'goteborg'."""
    return unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower().strip()


def _latin(text: str) -> bool:
    for ch in text:
        if ch.isalpha():
            try:
                if "LATIN" not in unicodedata.name(ch):
                    return False
            except ValueError:
                return False
    return True


def _alternates(name: str, asciiname: str, raw: str) -> list[str]:
    seen = {fold(name), asciiname.lower()}
    kept: list[str] = []
    for alt in raw.split(","):
        alt = alt.strip()
        if (
            len(alt) < 3
            or not alt[0].isupper()
            or alt.isupper()
            or any(ch.isdigit() for ch in alt)
            or "|" in alt
            or not _latin(alt)
        ):
            continue
        key = fold(alt)
        if key in seen:
            continue
        seen.add(key)
        kept.append(alt)
    return kept


def _fetch(name: str, local_dir: Path | None) -> bytes:
    artifact = by_name(name)
    if local_dir is not None:
        raw = (local_dir / artifact.upstream_path).read_bytes()
    else:
        raw = httpx.get(artifact.raw_url, timeout=120.0, follow_redirects=True).content
    digest = hashlib.sha256(raw).hexdigest()
    if digest != artifact.sha256:
        raise SystemExit(
            f"{artifact.upstream_path}: sha256 {digest} != recorded {artifact.sha256}.\n"
            "GeoNames republishes daily. To move to this snapshot, review the diff this "
            "generator produces, then record the new date and hash in tracker/vendored.py."
        )
    return raw


def build(cities_zip: bytes, admin1_txt: bytes) -> str:
    admin1: dict[str, str] = {}
    for line in admin1_txt.decode("utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) >= 3:
            admin1[parts[0]] = parts[2]

    by_alpha2 = {c.alpha2.upper(): c for c in COUNTRIES}
    with zipfile.ZipFile(io.BytesIO(cities_zip)) as archive:
        text = archive.read("cities15000.txt").decode("utf-8")

    rows: list[tuple[int, str]] = []
    for line in text.splitlines():
        f = line.split("\t")
        geonameid, name, asciiname, alternates = f[0], f[1], f[2], f[3]
        lat, lon, feature, country, admin1_code, population = f[4], f[5], f[7], f[8], f[10], f[14]
        if feature not in _KEEP_FEATURES or country not in by_alpha2:
            continue
        owner = by_alpha2[country]
        if fold(name) in {fold(owner.display), *owner.aliases}:
            continue
        row = (
            geonameid, name, asciiname, country, admin1_code,
            admin1.get(f"{country}.{admin1_code}", ""), population,
            f"{float(lat):.2f}", f"{float(lon):.2f}", feature,
            "|".join(_alternates(name, asciiname, alternates)),
        )
        rows.append((int(geonameid), "\t".join(row)))
    rows.sort()
    snapshot = by_name("geonames-cities15000").ref
    return _HEADER.format(snapshot=snapshot) + "\n".join(line for _, line in rows) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="diff against the committed file")
    ap.add_argument("--from", dest="local", type=Path, default=None, help="read the dumps from DIR")
    args = ap.parse_args()

    table = build(
        _fetch("geonames-cities15000", args.local),
        _fetch("geonames-admin1", args.local),
    )
    if args.check:
        current = _OUT.read_text(encoding="utf-8") if _OUT.exists() else ""
        if current != table:
            print(f"{_OUT} is out of date; rerun without --check", file=sys.stderr)
            return 1
        print("cities.tsv is current")
        return 0
    _OUT.write_text(table, encoding="utf-8")
    print(f"wrote {table.count(chr(10)) - 4} cities to {_OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
