// Copy compiler (docs/copy.md, section 2).
//
// Reads src/copy/<locale>/*.ftl with the official Fluent parser and writes:
//   src/copy/gen/<file>.ts         English messages as functions, each wrapped by
//                                  `m(id, en)`: the active table wins, English is the
//                                  fallback. The bundler places each export per chunk.
//   src/copy/gen/locales/<loc>.ts  every other locale as ONE table of functions,
//                                  indexed by a build-local id (the key's position in
//                                  the sorted English catalog), loaded on activate.
//   src/copy/gen/index.ts          the manifest and the locale loaders.
//   src/copy/gen/registry.ts       key -> English function, for tests' `msg()`;
//                                  no app module imports it.
// Pseudo locales come from the English AST: en-XA (accented, padded, bracketed)
// and keys (each message renders its key).
//
// Only a declared subset of Fluent compiles; anything else fails the build with
// file and line, where the Fluent runtime would drop the message silently.
// Terms are per locale and resolved at compile time: a term's arguments are
// literals, so its variant is chosen here, never at runtime. Plural selection
// in English messages uses English rules (`SE`), in a table its own (`S`).
//
//   node scripts/gen-copy.mjs          write
//   node scripts/gen-copy.mjs --check  exit 1 if a generated file is stale
import yaml from "js-yaml";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const DEFAULT_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "copy");
const CATEGORIES = new Set(["zero", "one", "two", "few", "many", "other"]);
const HEADER = "// GENERATED by scripts/gen-copy.mjs from src/copy/**/*.ftl. Do not edit.\n";

export { CopyError, metadata, readLocale } from "./copy/catalog.mjs";
import { CopyError, camel, readLocale, manifestAt, parity, dependencies, semantic, contract,branches } from "./copy/catalog.mjs";
const lit = (s) => JSON.stringify(s);

/** Compile one pattern to a JS expression over `a` (the message's arguments). */
function compilePattern(msg, terms, locale, { text = (s) => s, rtl = false, sel = "S", target = "ts" } = {}) {
  const vars = new Map(); // name -> "number" | "string" | "any"
  const plural = new Intl.PluralRules(locale);
  const bad = (node, why) => {
    const line = node?.span ? msg.src.slice(0, node.span.start).split("\n").length : "?";
    throw new CopyError(`${msg.file}:${line}: ${msg.id}: ${why}`);
  };

  // A value known at compile time (inside a term, from its literal arguments).
  const staticMatch = (value, key) =>
    key.type === "NumberLiteral"
      ? typeof value === "number" && value === Number(key.value)
      : value === key.name || (typeof value === "number" && plural.select(value) === key.name);

  function pattern(p, scope) {
    const parts = p.elements.map((el) => (el.type === "TextElement" ? lit(text(el.value)) : expr(el.expression, scope)));
    return parts.length ? parts.join("+") : '""';
  }
  function staticValue(x, scope) {
    if (x.type === "StringLiteral") return x.parse().value;
    if (x.type === "NumberLiteral") return Number(x.value);
    if (x.type === "VariableReference" && scope.term) return scope.args[x.id.name];
    if (x.type === "TermReference" && x.attribute) {
      const t = terms.get(x.id.name) ?? bad(x, `unknown term -${x.id.name}`);
      const attr = t.node.attributes.find((a) => a.id.name === x.attribute.name) ?? bad(x, `term -${x.id.name} has no .${x.attribute.name}`);
      return attr.value.elements.map((el) => el.value ?? "").join("");
    }
    return undefined;
  }
  function expr(x, scope) {
    switch (x.type) {
      case "StringLiteral":
        return lit(text(x.parse().value));
      case "NumberLiteral":
        return lit(x.value);
      case "VariableReference": {
        if (scope.term) {
          const v = scope.args[x.id.name];
          return v === undefined ? '""' : lit(String(v));
        }
        if (!vars.has(x.id.name)) vars.set(x.id.name, "any");
        const place = target === "python" ? `_f(a[${lit(x.id.name)}])` : `F(a.${x.id.name})`;
        return rtl ? `"\\u2068"+${place}+"\\u2069"` : place;
      }
      case "TermReference": {
        if (x.attribute) bad(x, "a term attribute is only for selectors");
        const t = terms.get(x.id.name) ?? bad(x, `unknown term -${x.id.name} in ${locale}`);
        const args = {};
        for (const n of x.arguments?.named ?? []) args[n.name.name] = staticValue(n.value, scope);
        if (x.arguments?.positional?.length) bad(x, "terms take named arguments only");
        return pattern(t.node.value, { term: true, args });
      }
      case "SelectExpression": {
        const known = staticValue(x.selector, scope);
        if (known !== undefined || scope.term) {
          // Resolved now: a term's own literal argument, or a term attribute.
          const hit = x.variants.find((v) => known !== undefined && staticMatch(known, v.key)) ?? x.variants.find((v) => v.default);
          return pattern(hit.value, scope);
        }
        if (x.selector.type !== "VariableReference") bad(x.selector, "a selector is a $variable or a term attribute");
        const name = x.selector.id.name;
        // Plural only when a key says so: a number, or a category other than
        // `other`, which is also every string select's natural default.
        const numeric = x.variants.some((v) => v.key.type === "NumberLiteral" || (CATEGORIES.has(v.key.name) && v.key.name !== "other"));
        vars.set(name, numeric || vars.get(name) === "number" ? "number" : "string");
        // Same order as @fluent/bundle: the first variant that matches wins,
        // the default variant included; the default again if none matches.
        const def = x.variants.find((v) => v.default);
        // A default variant that comes last needs no case of its own: the
        // fallback is the same text, and nothing after it could match first.
        const cases = x.variants.at(-1).default ? x.variants.slice(0, -1) : x.variants;
        const chain = cases.map((v) => {
          const key = v.key.type === "NumberLiteral" ? Number(v.key.value) : v.key.name;
          const test = target === "python" ? `_se(a[${lit(name)}],${lit(key)})` : `${sel}(a.${name},${lit(key)})`;
          return target === "python" ? `${pattern(v.value, scope)} if ${test} else ` : `${test}?${pattern(v.value, scope)}:`;
        });
        return `(${chain.join("")}${pattern(def.value, scope)})`;
      }
      case "Placeable":
        return expr(x.expression, scope);
      case "MessageReference":
        return bad(x, "a message never includes another message; use a term");
      case "FunctionReference":
        return bad(x, `${x.id.name}() is not in the subset; the format module owns formatting`);
      default:
        return bad(x, `${x.type} is not in the subset`);
    }
  }
  const body = pattern(msg.pattern, { term: false });
  return { body, vars };
}

/** The English a reader sees, for the JSDoc: default variants, `{$name}` for values. */
export function flatten(p, terms) {
  return p.elements
    .map((el) => {
      if (el.type === "TextElement") return el.value;
      const x = el.expression;
      if (x.type === "VariableReference") return `{$${x.id.name}}`;
      if (x.type === "StringLiteral") return x.parse().value;
      if (x.type === "TermReference") return terms.get(x.id.name) ? flatten(terms.get(x.id.name).node.value, terms) : "";
      if (x.type === "SelectExpression") return flatten(x.variants.find((v) => v.default).value, terms);
      return "";
    })
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}

const argType = (vars) =>
  vars.size
    ? `a: { ${[...vars].map(([k, t]) => `${k}: ${t === "number" ? "number" : t === "string" ? "string" : "string | number"}`).join("; ")} }`
    : "";

/** The runtime helpers a generated module actually calls. */
const helpers = (code, names, always = []) => [...names.filter((n) => new RegExp(`\\b${n}\\(`).test(code)), ...always].join(", ");

// --- Pseudo locales ---------------------------------------------------------
const ACCENT = Object.fromEntries([..."abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"].map((c, i) =>
  [c, "àƀçðéƒĝĥîĵķļɱñöþǫŕšţûṽŵẋýžÀßÇÐÉƑĜĤÎĴĶĻṀÑÖÞǪŔŠŢÛṼŴẊÝŽ"[i]]));
const accent = (s) => [...s].map((c) => ACCENT[c] ?? c).join("");
const pad = (s) => "·".repeat(Math.ceil(s.replace(/\s/g, "").length * 0.35));

/**
 * Compile a catalog. `runtime` is the import specifier the generated English
 * modules use for the runtime (tables use it one directory deeper).
 * Returns { files: Map<path, content>, report, ids }.
 */
export function build({ root = DEFAULT_ROOT, gen = join(root, "gen"), runtime = "../runtime", twin = true, catalogs = new Map() } = {}) {
  const manifest = manifestAt(root);
  const tableRuntime = runtime.startsWith(".") ? `../${runtime}` : runtime;
  const out = new Map();
  const catalog = (code) => { if (!catalogs.has(code)) catalogs.set(code, readLocale(root, code)); return catalogs.get(code); };
  const en = catalog("en");
  const quarantinePath = join(root, "translation-quarantine.json");
  const quarantine = existsSync(quarantinePath) ? JSON.parse(readFileSync(quarantinePath, "utf8")) : {};

  // A file the shell imports ships every message in it, ids included.
  // Its messages are numbered first,
  // so a message added to a lazy file never renumbers the shell's, and the
  // shell's bytes move only when the shell's own copy does.
  const rank = (x) => (x.eager ? 0 : 1);
  const ids = [...en.messages].sort((x, y) => rank(x) - rank(y) || (x.id < y.id ? -1 : x.id > y.id ? 1 : 0)).map((x) => x.id);
  const idOf = new Map(ids.map((id, i) => [id, i]));
  for (const [id, n] of Object.entries(Object.groupBy(en.messages, (x) => x.id))) {
    if (n.length > 1) throw new CopyError(`en: ${id} is defined ${n.length} times (${n.map((x) => x.file).join(", ")})`);
  }

  const names = new Map();
  for (const msg of en.messages) {
    if (names.has(camel(msg.id))) throw new CopyError(`${msg.file}: export collision ${msg.id} and ${names.get(camel(msg.id))}`);
    names.set(camel(msg.id), msg.id);
    dependencies(msg);
    branches(msg.pattern,en.terms);
  }
  for (const id of manifest.englishOnly ?? []) if (!idOf.has(id)) throw new CopyError(`unknown English-only message ${id}`);
  const signatures = new Map();
  const modules = [];
  for (const [file, list] of Object.entries(Object.groupBy(en.messages, (x) => x.file))) {
    let ts = "";
    for (const msg of list) {
      const { body, vars } = compilePattern(msg, en.terms, "en", { sel: "SE" });
      signatures.set(msg.id, vars);
      const doc = `${lit(flatten(msg.pattern, en.terms))}${msg.comment ? ` (${msg.comment.replace(/\n/g, " ")})` : ""}`.replace(/\*\//g, "* /");
      // A message with no arguments is passed as its text: `m` makes it a function.
      const english = vars.size === 0 && /^"(?:[^"\\]|\\.)*"$/.test(body) ? `${body} as const` : `(${argType(vars)}): string => ${body}`;
      // Pure, so a message nothing imports is dropped from the bundle
      // (a module-level call needs the annotation).
      const selectors = [...contract(msg.pattern).selectors.keys()];
      const typed = selectors.length ? ` as Message<${argType(vars).slice(3)}, ${selectors.map(lit).join(" | ")}>` : "";
      ts += `\n/** ${doc} */\nexport const ${camel(msg.id)} = /*#__PURE__*/ m(${idOf.get(msg.id)}, ${english})${typed};\n`;
    }
    // A `keyed` file is looked up by a key the data names (a slug the API
    // sends): it also exports every message by its key. The map keeps all of
    // them in the chunk that imports it, so such a file holds lookups only.
    if (en.keyed.has(file)) {
      const rows = list.filter((x) => !x.id.includes(".")).map((x) => `  ${lit(x.id)}: ${camel(x.id)},`).join("\n");
      ts += `\n/** Every message of this file by its key, for a lookup the data decides. */\nexport const byKey: Record<string, (a?: any) => string> = {\n${rows}\n};\n`;
    }
    const name = file.replace(/^en\//, "").replace(/\.ftl$/, "");
    modules.push({ name, ids: list.map((x) => x.id) });
    out.set(join(gen, `${name}.ts`), `${HEADER}import { ${helpers(ts, ["F", "SE", "m"], ts.includes(" as Message<") ? ["type Message"] : [])} } from ${lit(runtime)};\n${ts}`);
  }

  out.set(
    join(gen, "registry.ts"),
    `${HEADER}// Key -> English message, for tests (\`src/test/msg.ts\`). No app module imports this.\n${modules
      .map((mod) => `import * as ${camel(mod.name)} from "./${mod.name}";`)
      .join("\n")}\n\nexport const MESSAGES = {\n${modules
      .flatMap((mod) => mod.ids.map((id) => `  ${lit(id)}: ${camel(mod.name)}.${camel(id)},`))
      .join("\n")}\n} as const;\n`,
  );

  function table(locale, list, terms, { text, wrap = (b) => b, rtl = false } = {}) {
    const fns = new Array(ids.length).fill(null);
    for (const msg of list) {
      const i = idOf.get(msg.id);
      if (i === undefined) throw new CopyError(`${msg.file}: ${msg.id} is not in the English catalog`);
      dependencies(msg);
      if (locale !== "keys" && locale !== "en-XA") {
        const errors = parity(en.messages.find((e) => e.id === msg.id), msg);
        if (errors.length) {
          const saved = quarantine[msg.origin ?? locale]?.[msg.id];
          if (saved !== JSON.stringify(semantic(msg.pattern))) throw new CopyError(`${msg.file}: ${msg.id}: ${errors.join("; ")}`);
          continue; // Known mechanical defects stay visible; render the complete English message.
        }
      }
      const origin = msg.origin ?? locale;
      const grammar = origin === "keys" || origin === "en-XA" ? "en" : origin;
      const selector = origin !== locale ? `SL.bind(null,${lit(grammar)})` : "S";
      const { body, vars } = compilePattern(msg, msg.terms ?? terms, grammar, { text, rtl, sel: selector });
      const want = signatures.get(msg.id);
      for (const k of vars.keys()) if (!want.has(k)) throw new CopyError(`${msg.file}: ${msg.id} uses $${k}, which English does not pass`);
      const english = msg.pattern.elements.map((el) => el.value ?? "").join("");
      const fnBody = wrap(body, english, msg.id);
      // The parameter is named only when the code reads it: outside the string
      // literals, so a translation's own words ("…a.") never count, and a
      // select left with only its default reads nothing (Chinese plurals).
      const reads = /\ba\./.test(fnBody.replace(/"(?:[^"\\]|\\.)*"/g, '""'));
      fns[i] = `(${reads ? "a" : "_a"}: any): string => ${fnBody}`;
    }
    const filled = fns.filter(Boolean).length;
    const rows = fns.map((f) => `  ${f ?? "undefined"},`).join("\n");
    return {
      filled,
      ts: `${HEADER}import { ${helpers(rows, ["F", "S"], [...(rows.includes("SL.bind") ? ["SL"] : []), "type Table"])} } from ${lit(tableRuntime)};\n\nexport const filled = ${filled};\nexport default [\n${rows}\n] as Table;\n`,
    };
  }

  const report = [];
  for (const loc of manifest.locales) {
    if (loc.code === "en") continue;
    let t;
    if (loc.status === "pseudo" && loc.code === "en-XA") {
      // Accented, padded ~35% and bracketed, so unextracted text and clipped
      // layouts both show. Parameter values are not transformed: they are data.
      t = table(loc.code, en.messages, en.terms, { text: accent, wrap: (b, english) => `"⟦"+(${b})+${lit(pad(english))}+"⟧"` });
    } else if (loc.status === "pseudo" && loc.code === "keys") {
      // Each message renders its own key, for screenshots of which message is where.
      t = table(loc.code, en.messages, en.terms, { wrap: (_b, _e, id) => lit(`⟦${id}⟧`) });
    } else {
      const l = catalog(loc.code);
      for (const msg of l.messages) if ((manifest.englishOnly ?? []).includes(msg.id)) throw new CopyError(`${msg.file}: ${msg.id} is deliberately English-only`);
      const merged = new Map(l.messages.map(m => [m.id,m]));
      function addFallback(code) {
        if (code === "en") return;
        const fallback = catalog(code);
        for (const msg of fallback.messages) if (!merged.has(msg.id)) merged.set(msg.id,{...msg,origin:code});
        const declared = manifest.locales.find(l=>l.code===code);
        for (const next of declared.fallback ?? []) addFallback(next);
      }
      for (const code of loc.fallback ?? []) addFallback(code);
      t = table(loc.code, [...merged.values()], l.terms, { rtl: loc.dir === "rtl" });
      const missing = ids.filter((id) => (!l.messages.some((m) => m.id === id) || quarantine[loc.code]?.[id]) && !(manifest.englishOnly ?? []).includes(id));
      if (loc.status === "complete" && missing.length) {
        throw new CopyError(`${loc.code} is complete but ${missing.length} messages are missing`);
      }
    }
    out.set(join(gen, "locales", `${loc.code}.ts`), t.ts);
    report.push(`${loc.code} ${t.filled}/${ids.length}`);
  }

  out.set(
    join(gen, "index.ts"),
    `${HEADER}import type { Locale, Table } from ${lit(runtime)};\n\nexport const REGIONS: string[] = ${JSON.stringify(manifest.regions ?? [])};\n\nexport const LOCALES: Locale[] = ${JSON.stringify(manifest.locales, null, 2)};\n\nexport const LOADERS: Record<string, () => Promise<{ default: Table }>> = {\n${manifest.locales
      .filter((l) => l.code !== "en")
      .map((l) => `  ${lit(l.code)}: () => import("./locales/${l.code}"),`)
      .join("\n")}\n};\n`,
  );
  if (root === DEFAULT_ROOT) {
    const keysPath = join(root, "../../../backend/tests/fixtures/notification_keys.json");
    const keys = JSON.parse(readFileSync(keysPath,"utf8"));
    const aliases = { "notif-fit-fair": "shared-fit-band-some", "notif-fit-good": "shared-fit-band-good", "notif-fit-strong": "shared-fit-band-strong", "notif-fit-weak": "shared-fit-band-weak" };
    const rows = [], tsRows = [], contracts = [];
    for (const [key, params] of Object.entries(keys)) {
      const msg = en.messages.find((m) => m.id === (aliases[key] ?? key));
      if (!msg) throw new CopyError(`notification key ${key} has no catalog message`);
      const { body, vars } = compilePattern(msg,en.terms,"en",{target:"python"});
      if (JSON.stringify([...vars.keys()].sort()) !== JSON.stringify([...params].sort())) throw new CopyError(`${key}: durable notification parameters differ`);
      rows.push(`    ${lit(key)}: lambda a: ${body},`);
      contracts.push(`    ${lit(key)}: ${lit(params)},`);
      tsRows.push(`  ${lit(key)}: [${camel(msg.id)}, ${lit(params)}],`);
    }
    const bannerRows = en.messages.filter(m => m.id.startsWith("banner-")).map(msg => {
      const {body} = compilePattern(msg,en.terms,"en",{target:"python"});
      return `    ${lit(msg.id)}: lambda a: ${body},`;
    });
    const backend = join(root,"../../../backend/tracker/notifications/catalog_gen.py");
    if (twin) out.set(backend, `# GENERATED by dashboard/scripts/gen-copy.mjs. Do not edit.\nfrom tracker.notifications.catalog_format import _f, _se\n\nMESSAGES = {\n${rows.join("\n")}\n}\n\nPARAMETERS = {\n${contracts.join("\n")}\n}\n\nBANNERS = {\n${bannerRows.join("\n")}\n}\n`);
    const imports = [...new Set(Object.keys(keys).map((k) => aliases[k] ?? k))];
    const grouped = Object.groupBy(imports,(id) => en.messages.find((m) => m.id === id).file.replace("en/", "").replace(".ftl",""));
    out.set(join(gen,"notification-contract.ts"), `${HEADER}${Object.entries(grouped).map(([file,ids]) => `import { ${ids.map(camel).join(", ")} } from "./${file}";`).join("\n")}\nexport const NOTIFICATION_MESSAGES = {\n${tsRows.join("\n")}\n} as const;\n`);
  }
  if (root === DEFAULT_ROOT && twin) {
    // The backend's copy of the English rules, for its twin of copy:check
    // (`backend/tests/test_copy_glossary.py`). Written here so `--check`, which the
    // dashboard suite runs, fails when it is stale.
    const rules = yaml.load(readFileSync(join(root, "en", "glossary.yaml"), "utf8"));
    const twin = {
      banned: rules.banned ?? [],
      retired: rules.retired ?? [],
      forbid: rules.mechanics?.forbid ?? [],
      contractions: rules.mechanics?.contractions ?? {},
      allowed_phrases: rules.allowed?.phrases ?? [],
    };
    out.set(join(root, "..", "..", "..", "backend", "tests", "fixtures", "copy_glossary.gen.json"), JSON.stringify(twin, null, 2) + "\n");
  }
  return { files: out, report, ids };
}

/** Write (or with `check`, compare) the compiled files; returns the stale paths.
 *  With `gen`, a module there the build does not make is stale too, and is
 *  removed: a locale taken out of `locales.json` leaves no table behind. */
export function write(files, { check = false, gen = null } = {}) {
  // Every entry point uses the same orphan cleanup, including Vite and UX.
  if (!gen) gen = [...files.keys()].find((p) => p.endsWith("/registry.ts"))?.slice(0, -12) ?? null;
  const stale = [];
  for (const [path, content] of files) {
    const now = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (now === content) continue;
    stale.push(path);
    if (!check) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  const orphans = (dir) =>
    existsSync(dir)
      ? readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
          const path = join(dir, entry.name);
          if (entry.isDirectory()) return orphans(path);
          return entry.name.endsWith(".ts") && !files.has(path) ? [path] : [];
        })
      : [];
  for (const path of gen ? orphans(gen) : []) {
    stale.push(path);
    if (!check) rmSync(path);
  }
  return stale;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  // `--no-twin`: the npm hooks regenerate src/copy/gen/ only; the backend twin is
  // committed, and only `npm run gen:copy` rewrites it (so `--check` can see it stale).
  const twin = !process.argv.includes("--no-twin");
  try {
    const { files, report, ids } = build({ twin });
    const stale = write(files, { check, gen: join(DEFAULT_ROOT, "gen") });
    for (const path of check ? stale : []) console.error(`stale: ${path}`);
    console.log(`gen:copy ${ids.length} messages; ${report.join(", ")}; ${check ? (stale.length ? `${stale.length} stale` : "up to date") : `${stale.length} written`}`);
    if (check && stale.length) process.exit(1);
  } catch (error) {
    if (!(error instanceof CopyError)) throw error;
    console.error(`gen:copy: ${error.message}`);
    process.exit(1);
  }
}
